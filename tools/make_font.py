# accents : (forme, ligne de départ relative au haut du glyphe, ancré sur une minuscule ?)
ACC = {
    "aigu": ["..#", ".#."],
    "grave": ["#..", ".#."],
    "circ": [".#.", "#.#"],
    "trema": ["#.#"],
    "cedille": [".#", "#."],
}
COMPOSE = {
    "à": ("a", "grave"), "â": ("a", "circ"), "ä": ("a", "trema"),
    "é": ("e", "aigu"), "è": ("e", "grave"), "ê": ("e", "circ"), "ë": ("e", "trema"),
    "î": ("i", "circ"), "ï": ("i", "trema"), "ô": ("o", "circ"), "ö": ("o", "trema"),
    "ù": ("u", "grave"), "û": ("u", "circ"), "ü": ("u", "trema"), "ç": ("c", "cedille"),
    "À": ("A", "grave"), "Â": ("A", "circ"), "É": ("E", "aigu"), "È": ("E", "grave"),
    "Ê": ("E", "circ"), "Î": ("I", "circ"), "Ô": ("O", "circ"), "Ç": ("C", "cedille"),
    "Ù": ("U", "grave"), "Û": ("U", "circ"), "ë": ("e", "trema"),
}


def glyph_bitmap(ch):
    """Retourne (lignes sur H de haut, largeur)."""
    if ch in COMPOSE:
        base, acc = COMPOSE[ch]
        rows = [r for r in glyph_bitmap(base)[0]]
        w = len(rows[TOP])
        a = ACC[acc]
        aw = len(a[0])
        ox = max(0, (w - aw + 1) // 2)
        if acc == "cedille":
            y0 = TOP + 7
        elif base.islower():
            y0 = TOP + 2 - len(a)
        else:
            y0 = TOP - len(a)
        if base == "i":
            # le point du i est remplacé par l'accent
            rows[TOP] = "." * w
            w = max(w, aw)
            rows = [r.ljust(w, ".") for r in rows]
            ox = (w - aw) // 2
        rows = [list(r) for r in rows]
        for j, line in enumerate(a):
            for i, c in enumerate(line):
                if c == "#" and 0 <= y0 + j < H and ox + i < w:
                    rows[y0 + j][ox + i] = "#"
        return ["".join(r) for r in rows], w
    g = G[ch]
    w = len(g[0])
    rows = ["." * w] * TOP + g + ["." * w] * (9 - len(g))
    return rows, w


def main():
    os.makedirs(OUT, exist_ok=True)
    chars = sorted(set(G) | set(COMPOSE), key=ord)
    cols = 16
    cw = 8
    sheet = Image.new("RGBA", (cols * cw, ((len(chars) + cols - 1) // cols) * H), (0, 0, 0, 0))
    px = sheet.load()
    lines = []
    for n, ch in enumerate(chars):
        rows, w = glyph_bitmap(ch)
        assert all(len(r) == w for r in rows), ch
        x0, y0 = (n % cols) * cw, (n // cols) * H
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c == "#":
                    px[x0 + x, y0 + y] = (255, 255, 255, 255)
        adv = w + 1
        lines.append("char id=%d x=%d y=%d width=%d height=%d xoffset=0 yoffset=0 xadvance=%d page=0 chnl=15" % (ord(ch), x0, y0, w, H, adv))
    sheet.save(os.path.join(OUT, "brume.png"))
    with open(os.path.join(OUT, "brume.fnt"), "w") as f:
        f.write('info face="Brume" size=%d bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1 outline=0\n' % H)
        f.write("common lineHeight=%d base=%d scaleW=%d scaleH=%d pages=1 packed=0 alphaChnl=0 redChnl=4 greenChnl=4 blueChnl=4\n" % (H, TOP + 7, sheet.width, sheet.height))
        f.write('page id=0 file="brume.png"\n')
        f.write("chars count=%d\n" % len(lines))
        f.write("\n".join(lines) + "\n")
    print("ok :", len(chars), "glyphes")


if __name__ == "__main__":
    main()
